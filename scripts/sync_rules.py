#!/usr/bin/env python3
"""将 rule_sources.json 中的公开上游规则转换为独立的 Loon 订阅。"""

import argparse
import ipaddress
import json
import re
import sys
from pathlib import PurePosixPath

from update_rules import ROOT, digest, fetch


def parse_rules(text, domain_set=False):
    """保持原顺序及 IP 选项；未知语法直接报错，避免悄悄丢失覆盖范围。"""
    rules = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith(("#", ";", "//")):
            continue
        if domain_set:
            # 上游 .example.com 表示包含子域名，无前导点表示精确域名。
            kind = "DOMAIN-SUFFIX" if line.startswith(".") else "DOMAIN"
            fields = [kind, line.removeprefix(".")]
        else:
            fields = [part.strip() for part in line.split(",")]
        if len(fields) not in {2, 3} or not all(fields):
            raise ValueError(f"Line {number}: invalid rule {line!r}")
        kind, value, *options = fields
        kind = kind.upper()
        if options and (options != ["no-resolve"] or kind not in {"IP-CIDR", "IP-CIDR6", "IP-ASN"}):
            raise ValueError(f"Line {number}: unexpected policy/options {line!r}")
        if kind in {"DOMAIN", "DOMAIN-SUFFIX"}:
            value = value.lower().rstrip(".")
            if not re.fullmatch(r"[a-z0-9_](?:[a-z0-9_.-]*[a-z0-9_])?", value):
                raise ValueError(f"Line {number}: invalid domain {value!r}")
        elif kind in {"IP-CIDR", "IP-CIDR6"}:
            network = ipaddress.ip_network(value, strict=True)
            if network.version != (4 if kind == "IP-CIDR" else 6) or network.prefixlen == 0:
                raise ValueError(f"Line {number}: invalid IP range {value!r}")
        elif kind == "IP-ASN":
            if not value.isdecimal() or not 1 <= int(value) <= 4294967295:
                raise ValueError(f"Line {number}: invalid ASN {value!r}")
        elif kind not in {"DOMAIN-KEYWORD", "USER-AGENT"}:
            raise ValueError(f"Line {number}: unsupported type {kind!r}")
        rules.append(",".join([kind, value, *options]))
    if not 1 <= len(rules) <= 100000:
        raise ValueError(f"Unexpected rule count: {len(rules)}")
    return list(dict.fromkeys(rules))


def collect():
    config = json.loads((ROOT / "rule_sources.json").read_text(encoding="utf-8"))
    outputs, records, counts = {}, {}, {}
    for repo, settings in config.items():
        if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
            raise ValueError(f"Invalid repository: {repo}")
        branch = settings["branch"]
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", branch):
            raise ValueError(f"Invalid branch: {branch}")
        # Git ref 接口只返回分支指针，避免下载大型提交的文件差异。
        revision = json.loads(fetch(f"https://api.github.com/repos/{repo}/git/ref/heads/{branch}"))["object"]["sha"]
        if not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise ValueError("Invalid upstream revision")
        records[repo] = {"revision": revision, "license": settings["license"], "files": {}}
        for name, paths in settings["rules"].items():
            if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", name) or name in counts or name == "AI":
                raise ValueError(f"Invalid or repeated category: {name}")
            if not isinstance(paths, list) or not paths:
                raise ValueError(f"Missing source files: {name}")
            rules = []
            for source_path in paths:
                if not re.fullmatch(r"[A-Za-z0-9_./-]+", source_path) or any(
                    part in {"..", "."} for part in PurePosixPath(source_path).parts
                ) or source_path.startswith("/"):
                    raise ValueError(f"Invalid source path: {source_path}")
                url = f"https://raw.githubusercontent.com/{repo}/{revision}/{source_path}"
                content = fetch(url)
                rules.extend(parse_rules(content, source_path.endswith("_Domain.list")))
                records[repo]["files"][source_path] = {"url": url, "sha256": digest(content)}
            rules = list(dict.fromkeys(rules))
            path = ROOT / "Rules" / name / f"{name}.list"
            header = [f"# {name}.list - generated by scripts/sync_rules.py; DO NOT EDIT",
                      f"# Source and author: {repo} ({settings['license']})",
                      f"# Revision: {revision}",
                      "# Modified by MyRules on 2026-11-08: convert domain sets and deduplicate.",
                      "# License and notices: THIRD_PARTY_NOTICES.md and LICENSES/", ""]
            outputs[path] = "\n".join([*header, *rules, ""])
            counts[name] = len(rules)
    manifest = {"repositories": records, "counts": counts}
    outputs[ROOT / "rules.lock.json"] = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    return outputs, counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--accept-removals", action="store_true",
                        help="Accept large removals after reviewing upstream changes")
    args = parser.parse_args()
    outputs, counts = collect()
    # 所有来源下载、解析成功后再检查删减，最后才写文件。
    for path, content in outputs.items():
        if path.suffix != ".list" or not path.exists() or args.accept_removals:
            continue
        old = set(parse_rules(path.read_text(encoding="utf-8")))
        new = set(parse_rules(content))
        if len(old - new) > len(old) * 0.25:
            raise ValueError(f"{path.name}: over 25% of previous rules removed; review sources first")
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.with_suffix(path.suffix + ".tmp").write_text(content, encoding="utf-8")
    for path in outputs:
        path.with_suffix(path.suffix + ".tmp").replace(path)
    for name, count in counts.items():
        print(f"{name}: {count} rules")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Update failed: {error}", file=sys.stderr)
        sys.exit(1)
